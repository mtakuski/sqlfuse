"""Database migrations.

* :class:`Migrator` — Alembic, driven programmatically (no ``alembic.ini`` required).
* :func:`sync_schema` — dev helper: create missing tables / add missing columns, never drops.

CLI::

    python -m sqlfuse.migrations --url sqlite:///app.db --models app.models init
    python -m sqlfuse.migrations --url sqlite:///app.db --models app.models revision -m "add hero"
    python -m sqlfuse.migrations --url sqlite:///app.db --models app.models upgrade
    python -m sqlfuse.migrations --url sqlite:///app.db --models app.models downgrade -1
"""
