def render_item(type_: str, obj: Any, autogen_context: Any) -> Any:
    """Alembic hook: render sqlfuse custom types as portable SQLAlchemy types."""
    if type_ == "type" and isinstance(obj, PydanticJSON):
        autogen_context.imports.add("import sqlalchemy as sa")
        return "sa.JSON()"
    return False


class Migrator:
    """Alembic wrapper bound to one database URL, models module and scripts directory."""

    def __init__(self, url: str, models_module: str | None = None,
                 directory: str | os.PathLike = "migrations"):
        self.url = url
        self.models_module = models_module or ""
        self.directory = Path(directory)

    @property
    def config(self):
        from alembic.config import Config

        cfg = Config()
        cfg.set_main_option("script_location", str(self.directory))
        cfg.set_main_option("sqlalchemy.url", self.url.replace("%", "%%"))
        cfg.attributes["url"] = self.url
        cfg.attributes["models_module"] = self.models_module
        return cfg

    def init(self) -> Path:
        """Create the migrations directory (env.py, script template, versions/)."""
        import alembic

        if (self.directory / "env.py").exists():
            return self.directory
        (self.directory / "versions").mkdir(parents=True, exist_ok=True)
        (self.directory / "env.py").write_text(ENV_PY)
        template = Path(alembic.__file__).parent / "templates" / "generic" / "script.py.mako"
        shutil.copy(template, self.directory / "script.py.mako")
        return self.directory

    def revision(self, message: str, *, autogenerate: bool = True, rev_id: str | None = None):
        from alembic import command

        self.init()
        return command.revision(self.config, message=message, autogenerate=autogenerate, rev_id=rev_id)

    def upgrade(self, revision: str = "head", *, sql: bool = False) -> None:
        from alembic import command

        command.upgrade(self.config, revision, sql=sql)

    def downgrade(self, revision: str = "-1", *, sql: bool = False) -> None:
        from alembic import command

        command.downgrade(self.config, revision, sql=sql)

    def stamp(self, revision: str = "head") -> None:
        from alembic import command

        command.stamp(self.config, revision)

    def current(self) -> str | None:
        from alembic.runtime.migration import MigrationContext

        from .session import is_async_url

        if is_async_url(self.url):
            raise RuntimeError("current() needs a sync URL; use the CLI or a sync driver")
        engine = sa.create_engine(self.url)
        try:
            with engine.connect() as conn:
                return MigrationContext.configure(conn).get_current_revision()
        finally:
            engine.dispose()

    def history(self) -> list[str]:
        from alembic.script import ScriptDirectory

        script = ScriptDirectory.from_config(self.config)
        return [f"{r.revision}: {r.doc}" for r in script.walk_revisions()]


# --------------------------------------------------------------------------- dev helper

def _sync_schema(conn: Connection, metadata: sa.MetaData) -> list[str]:
    applied: list[str] = []
    insp = sa.inspect(conn)
    existing = set(insp.get_table_names())
    missing = [t for t in metadata.sorted_tables if t.name not in existing]
    if missing:
        metadata.create_all(conn, tables=missing)
        applied += [f"CREATE TABLE {t.name}" for t in missing]
    for table in metadata.sorted_tables:
        if table.name not in existing:
            continue
        have = {c["name"] for c in insp.get_columns(table.name)}
        for column in table.columns:
            if column.name in have:
                continue
            if not column.nullable and column.server_default is None:
                raise RuntimeError(
                    f"Cannot add NOT NULL column {table.name}.{column.name} without a "
                    "server_default; use a migration (Migrator) instead"
                )
            ddl = sa.schema.CreateColumn(column).compile(dialect=conn.dialect)
            stmt = f"ALTER TABLE {conn.dialect.identifier_preparer.quote(table.name)} ADD COLUMN {ddl}"
            conn.execute(sa.text(stmt))
            applied.append(stmt)
    return applied


def sync_schema(engine: Engine, metadata: sa.MetaData | None = None) -> list[str]:
    """Create missing tables and add missing nullable/defaulted columns. Returns applied DDL."""
    with engine.begin() as conn:
        return _sync_schema(conn, metadata or SQLBase.metadata)


async def async_sync_schema(engine: AsyncEngine, metadata: sa.MetaData | None = None) -> list[str]:
    async with engine.begin() as conn:
        return await conn.run_sync(_sync_schema, metadata or SQLBase.metadata)


# --------------------------------------------------------------------------- CLI

def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="python -m sqlfuse.migrations")
    parser.add_argument("--url", default=os.environ.get("SQLFUSE_DATABASE_URL"), required=False)
    parser.add_argument("--models", default=os.environ.get("SQLFUSE_MODELS", ""),
                        help="comma-separated modules that define your models")
    parser.add_argument("--dir", default="migrations")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init")
    rev = sub.add_parser("revision")
    rev.add_argument("-m", "--message", required=True)
    rev.add_argument("--empty", action="store_true", help="no autogenerate")
    up = sub.add_parser("upgrade")
    up.add_argument("revision", nargs="?", default="head")
    up.add_argument("--sql", action="store_true")
    down = sub.add_parser("downgrade")
    down.add_argument("revision", nargs="?", default="-1")
    down.add_argument("--sql", action="store_true")
    sub.add_parser("current")
    sub.add_parser("history")
    args = parser.parse_args(argv)
    if not args.url:
        parser.error("--url or SQLFUSE_DATABASE_URL is required")

    m = Migrator(args.url, args.models, args.dir)
    if args.cmd == "init":
        print(m.init())
    elif args.cmd == "revision":
        m.revision(args.message, autogenerate=not args.empty)
    elif args.cmd == "upgrade":
        m.upgrade(args.revision, sql=args.sql)
    elif args.cmd == "downgrade":
        m.downgrade(args.revision, sql=args.sql)
    elif args.cmd == "current":
        print(m.current())
    elif args.cmd == "history":
        print("\n".join(m.history()))


if __name__ == "__main__":
    main()
